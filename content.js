// The room code an offer belongs to. Accor used to inline the accommodation on
// every offer; newer payloads carry only `product.id`, which holds the same
// room code. Read both so either version groups correctly. page-bridge.js
// normalizes this too — this is the second line of defence, for offers that
// reach us straight from Apollo's cache.
function getOfferRoomCode(offer) {
  return (offer.accommodation && offer.accommodation.code)
    || (offer.product && offer.product.id)
    || null;
}

// Pre-index all BestOfferInfo entries by accommodation ref, code, and name (called once per cache)
function buildOfferIndex(cache) {
  const byRef = new Map();   // accommodation.__ref → [offers]
  const byCode = new Map();  // accommodation.code → [offers]
  const byName = new Map();  // accommodation.name → [offers]
  for (const k of Object.keys(cache)) {
    if (!k.startsWith('BestOfferInfo:')) continue;
    const v = cache[k];
    const code = getOfferRoomCode(v);
    // No room identity at all — nothing to group this offer under.
    if (!v.accommodation && !code) continue;
    const rateRef = (v.rate && v.rate.__ref) || '';
    // Apollo normalizes rate behind a __ref; GraphQL inlines it and
    // page-bridge.js pre-sets resolvedRate. Only the __ref path needs a
    // lookup — overwriting unconditionally used to blank out every rate label.
    const rateInfo = cache[rateRef] || v.resolvedRate || v.rate || {};
    const entry = Object.assign({}, v, { resolvedRate: rateInfo, cacheKey: k });
    const ref = v.accommodation && v.accommodation.__ref;
    if (ref) { if (!byRef.has(ref)) byRef.set(ref, []); byRef.get(ref).push(entry); }
    if (code) { if (!byCode.has(code)) byCode.set(code, []); byCode.get(code).push(entry); }
    const name = v.accommodation && v.accommodation.name;
    if (name) { if (!byName.has(name)) byName.set(name, []); byName.get(name).push(entry); }
  }
  return { byRef, byCode, byName };
}

function getOffersForRoom(roomEl, cache, validOfferIds, offerIndex) {
  const offerClass = [...roomEl.classList].find(c => c.startsWith('hotel-offer-'));
  if (!offerClass) {
    dbg('No hotel-offer- class on room. All classes:', [...roomEl.classList]);
    return [];
  }
  const bestOfferId = offerClass.replace('hotel-offer-', '');
  const bestOffer = cache['BestOfferInfo:' + bestOfferId];
  if (!bestOffer) {
    dbg('No BestOfferInfo:' + bestOfferId, 'in cache');
    return [];
  }

  const accommRef = (bestOffer.accommodation && bestOffer.accommodation.__ref) || null;
  const accommCode = getOfferRoomCode(bestOffer);
  const roomName = bestOffer.accommodation && bestOffer.accommodation.name;

  dbg('Room match criteria — ref:', accommRef, 'code:', accommCode, 'name:', roomName);

  // Use pre-built index for O(1) lookup instead of scanning entire cache
  let allOffers;
  if (accommRef && offerIndex.byRef.has(accommRef)) {
    allOffers = offerIndex.byRef.get(accommRef);
  } else if (accommCode && offerIndex.byCode.has(accommCode)) {
    allOffers = offerIndex.byCode.get(accommCode);
  } else if (roomName && offerIndex.byName.has(roomName)) {
    // Filter by valid page offer IDs or hotel match to prevent cross-hotel collisions
    const hotelIdMatch = location.pathname.match(/\/hotel\/([A-Za-z0-9]+)/i);
    const pageHotelId = hotelIdMatch ? hotelIdMatch[1] : null;
    allOffers = offerIndex.byName.get(roomName).filter(o => {
      const offerId = o.cacheKey.replace('BestOfferInfo:', '');
      if (validOfferIds && validOfferIds.has(offerId)) return true;
      if (pageHotelId && o.hotel) {
        const offerHotelCode = (typeof o.hotel === 'string') ? o.hotel :
          (o.hotel.code || o.hotel.id || (o.hotel.__ref || '').replace(/.*:/, ''));
        if (offerHotelCode === pageHotelId) return true;
      }
      if (!o.hotel) return true;
      return false;
    });
  } else {
    allOffers = [];
  }

  dbg('Found', allOffers.length, 'raw offers for', roomName);

  // Deduplicate by rate label + price
  const seen = new Set();
  const unique = allOffers.filter(o => {
    if (!o.pricing || !o.pricing.main || !o.pricing.main.amount) return false;
    const rateLabel = (o.resolvedRate && o.resolvedRate.label) || '';
    const amount = o.pricing.main.amount || 0;
    const key = rateLabel + '|' + amount;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });

  // Sort: ROOM type first, then by price ascending
  unique.sort((a, b) => {
    if (a.type !== b.type) return a.type === 'ROOM' ? -1 : 1;
    const aPrice = (a.pricing && a.pricing.main && a.pricing.main.amount) || 0;
    const bPrice = (b.pricing && b.pricing.main && b.pricing.main.amount) || 0;
    return aPrice - bPrice;
  });

  dbg('Returning', unique.length, 'unique offers for', roomName);
  return unique;
}

function buildRatePanel(offers, nights) {
  const panel = document.createElement('div');
  panel.className = 'ext-all-rates-panel';

  offers.forEach(offer => {
    const card = document.createElement('div');
    card.className = 'ext-rate-card';

    const rateName = (offer.resolvedRate && offer.resolvedRate.label) || 'Standard Rate';
    const memberPrice = (offer.pricing && offer.pricing.main && offer.pricing.main.formattedAmount) || '';
    const publicPrice = (offer.pricing && offer.pricing.alternative && offer.pricing.alternative.formattedAmount) || '';
    const deductions = (offer.pricing && offer.pricing.deduction) || [];
    const savings = deductions.length > 0 ? deductions[0].formattedAmount || '' : '';
    const simplifiedPolicies = (offer.pricing && offer.pricing.main && offer.pricing.main.simplifiedPolicies) || {};
    const cancellation = (simplifiedPolicies.cancellation && simplifiedPolicies.cancellation.label) || '';
    const cancellationCode = (simplifiedPolicies.cancellation && simplifiedPolicies.cancellation.code) || '';
    const mealPlan = (offer.mealPlan && offer.mealPlan.label) || '';
    const typeBadge = offer.type === 'PACKAGE' ? 'DEAL' : '';

    // Compute tax-inclusive total for this rate
    const tax = computeTaxData(offer, nights);

    // Column 1: Rate name + type badge
    const nameCol = document.createElement('div');
    nameCol.className = 'ext-rate-name';
    nameCol.textContent = rateName;
    if (typeBadge) {
      const badge = document.createElement('span');
      badge.className = 'ext-rate-type-badge';
      badge.textContent = typeBadge;
      nameCol.appendChild(badge);
    }

    // Column 2: Meal plan
    const mealCol = document.createElement('div');
    mealCol.className = 'ext-rate-meal';
    mealCol.textContent = mealPlan;

    // Column 3: Cancellation policy. NO_CANCELLATION is the code Accor actually
    // sends for non-refundable rates; matching only on the label's "non" left
    // the colour at the mercy of Accor's wording (and of the page language).
    const policyCol = document.createElement('div');
    policyCol.className = 'ext-rate-policy';
    const freeCancel = cancellationCode === 'FREE_CANCELLATION'
      || (!cancellationCode && cancellation.toLowerCase().includes('free'));
    const noCancel = cancellationCode === 'NO_CANCELLATION'
      || cancellationCode === 'NON_REFUNDABLE'
      || (!cancellationCode && cancellation.toLowerCase().includes('non'));
    if (freeCancel) {
      policyCol.classList.add('free-cancel');
    } else if (noCancel) {
      policyCol.classList.add('non-refundable');
    }
    // Fall back to the code's meaning when Accor sends one with no label.
    policyCol.textContent = cancellation
      || (freeCancel ? 'Free cancellation' : (noCancel ? 'Non-refundable' : ''));

    // Column 4: Can you put points against this rate?
    // Accor ships a per-offer ladder of point amounts it will convert into a
    // discount (loyaltyRewardPoint.thresholds). No ladder = cash only. This is
    // Accor's own per-rate answer, so it beats guessing from the price or the
    // cancellation policy — non-refundable room rates accept points just fine;
    // it's the package/promo rates that are usually excluded.
    const pointsThresholds = (offer.loyaltyRewardPoint && offer.loyaltyRewardPoint.thresholds) || [];
    const pointsCol = document.createElement('div');
    pointsCol.className = 'ext-rate-points ' + (pointsThresholds.length ? 'points-ok' : 'points-no');
    if (pointsThresholds.length) {
      const maxPoints = pointsThresholds[pointsThresholds.length - 1].points;
      pointsCol.textContent = '✓ Points';
      pointsCol.title = 'Points accepted on this rate, in steps of '
        + pointsThresholds.map(t => t.points).slice(0, 2).join(' / ')
        + ' up to ' + maxPoints.toLocaleString() + ' points';
    } else {
      pointsCol.textContent = 'Cash only';
      pointsCol.title = 'Accor offers no points conversion on this rate';
    }

    // Column 5: Prices with tax-inclusive total
    const priceCol = document.createElement('div');
    priceCol.className = 'ext-rate-price';

    if (tax) {
      // Tax-inclusive total: "Total: $275 w/ Tax ($92/night)"
      const totalLine = document.createElement('div');
      totalLine.className = 'ext-rate-total-line';
      let totalHtml = `Total: <span class="ext-rate-member-price">${tax.fmtTotal}</span> w/ Tax`;
      if (nights > 1) {
        totalHtml += ` <span class="ext-rate-per-night">(${tax.fmtPerNight}/night)</span>`;
      }
      totalLine.innerHTML = totalHtml;
      priceCol.appendChild(totalLine);

      // "From $242 + Taxes $33"
      const breakdownLine = document.createElement('div');
      breakdownLine.className = 'ext-rate-tax-breakdown';
      breakdownLine.textContent = `From ${tax.fmtBase} + Taxes ${tax.fmtTax}`;
      priceCol.appendChild(breakdownLine);
    } else {
      // No tax data — just show member price
      if (memberPrice) {
        const memberSpan = document.createElement('span');
        memberSpan.className = 'ext-rate-member-price';
        memberSpan.textContent = memberPrice;
        priceCol.appendChild(memberSpan);
      }
    }

    if (publicPrice && publicPrice !== memberPrice) {
      const publicSpan = document.createElement('div');
      publicSpan.className = 'ext-rate-public-price';
      publicSpan.textContent = publicPrice;
      priceCol.appendChild(publicSpan);
    }
    if (savings) {
      const savingsDiv = document.createElement('div');
      savingsDiv.className = 'ext-rate-savings';
      savingsDiv.textContent = 'Save ' + savings;
      priceCol.appendChild(savingsDiv);
    }

    card.appendChild(nameCol);
    card.appendChild(mealCol);
    card.appendChild(policyCol);
    card.appendChild(pointsCol);
    card.appendChild(priceCol);
    panel.appendChild(card);
  });

  return panel;
}

let showAllRatesRetryCount = 0;
const SHOW_ALL_RATES_MAX_RETRIES = 3;

async function injectAllRatePanels() {
  if (_extensionContextInvalidated) return; // orphaned script; stop the retry chain
  dbg('injectAllRatePanels() called');
  const cache = await extractApolloCacheViaPageScript();
  if (!cache) {
    dbg('Apollo cache returned null, retry', showAllRatesRetryCount);
    if (showAllRatesRetryCount < SHOW_ALL_RATES_MAX_RETRIES) {
      showAllRatesRetryCount++;
      setTimeout(() => {
        if (showAllRatesActive) injectAllRatePanels();
      }, 500);
    } else {
      dbg('Apollo cache not available after retries');
    }
    return;
  }
  showAllRatesRetryCount = 0;

  // Pre-index all offers once (O(n) scan), then O(1) lookups per room
  const offerIndex = buildOfferIndex(cache);
  const validOfferIds = getPageOfferIds();
  const nights = getNightsFromUrl();
  const roomSelector = findRoomsSelector();
  const rooms = document.querySelectorAll(roomSelector);


  rooms.forEach((roomEl, i) => {
    if (roomEl.querySelector('.ext-all-rates-panel')) return;
    if (roomEl.classList.contains('hotel-accommodation--selected')) return;
    if (roomEl.offsetHeight === 0) return;

    const offers = getOffersForRoom(roomEl, cache, validOfferIds, offerIndex);
    if (offers.length === 0) return;

    sendRateSnapshots(offers, getHotelIdFromUrl() || 'unknown', nights);

    const panel = buildRatePanel(offers, nights);
    // Try multiple insertion points
    const topInfos = roomEl.querySelector('.hotel-accommodation__top-infos')
      || roomEl.querySelector('[class*="top-infos"]')
      || roomEl.querySelector('[class*="room-info"]')
      || roomEl.querySelector('[class*="accommodation__top"]');
    if (topInfos) {
      topInfos.insertAdjacentElement('afterend', panel);
    } else {
      roomEl.appendChild(panel);
    }
  });
}

