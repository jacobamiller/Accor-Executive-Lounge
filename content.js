// ==================== PRICE HELPERS ====================
/**
 * Parse a localized number string into a float.
 * Handles US (1,350.00) and European (1.350,00) formats.
 */
function parseLocalizedNumber(str) {
  str = str.replace(/\s/g, '');
  if (str.includes(',') && str.includes('.')) {
    // Both separators: last one is the decimal
    if (str.lastIndexOf(',') > str.lastIndexOf('.')) {
      // European: 1.350,00
      return parseFloat(str.replace(/\./g, '').replace(',', '.'));
    }
    // US: 1,350.00
    return parseFloat(str.replace(/,/g, ''));
  }
  if (str.includes(',')) {
    // Single comma: decimal if followed by exactly 2 digits at end, else thousands
    if (/,\d{2}$/.test(str) && (str.match(/,/g) || []).length === 1) {
      return parseFloat(str.replace(',', '.'));
    }
    return parseFloat(str.replace(/,/g, ''));
  }
  return parseFloat(str);
}

/**
 * Extract currency symbol and numeric amount from a price string.
 * Supports prefix ($45, A$1,350) and suffix (1.350,00 €) currencies.
 */
function parseCurrencyAmount(text) {
  // Try prefix currency: $45, A$1,350, HK$200, €67,50
  let match = text.match(/([^\d\s.,]+)\s*([\d.,]+)/);
  if (match) {
    const amount = parseLocalizedNumber(match[2]);
    if (!isNaN(amount)) return { currency: match[1].trim(), amount };
  }
  // Try suffix currency: 1.350,00 €
  match = text.match(/([\d.,]+)\s*([^\d\s.,]+)/);
  if (match) {
    const amount = parseLocalizedNumber(match[1]);
    if (!isNaN(amount)) return { currency: match[2].trim(), amount };
  }
  return null;
}

// ==================== PRICE DATA PARSING ====================
function parsePriceData(card) {
  try {
    // Extract base price and currency from span.offer-price__amount
    const priceEl = card.querySelector('span.offer-price__amount');
    if (!priceEl) return null;
    const priceText = priceEl.textContent.trim();
    const priceResult = parseCurrencyAmount(priceText);
    if (!priceResult) return null;

    // Extract tax from span.stay-details__formatted-tax-type
    const taxEl = card.querySelector('span.stay-details__formatted-tax-type');
    if (!taxEl) return null;
    const taxText = taxEl.textContent.trim();
    const taxResult = parseCurrencyAmount(taxText);
    if (!taxResult) return null;

    // Extract nights from span.pricing-type-label
    const nightsEl = card.querySelector('span.pricing-type-label');
    if (!nightsEl) return null;
    const nightsText = nightsEl.textContent.trim();
    const nightsMatch = nightsText.match(/(\d+)\s*night/i);
    if (!nightsMatch) return null;
    const nights = parseInt(nightsMatch[1], 10);
    if (isNaN(nights) || nights < 1) return null;

    // Extract public (non-member) price if available
    let publicPrice = null;
    const publicSelectors = ['[class*="crossed"]', '[class*="barred"]', '[class*="public-price"]', 'del', 's'];
    for (const sel of publicSelectors) {
      const el = card.querySelector(sel);
      if (el) { const r = parseCurrencyAmount(el.textContent.trim()); if (r) { publicPrice = r.amount; break; } }
    }

    return {
      basePrice: priceResult.amount,
      tax: taxResult.amount,
      nights,
      currency: priceResult.currency,
      publicPrice,
      raw: { priceText, taxText, nightsText }
    };
  } catch (e) {
    return null;
  }
}


// ==================== TAX-INCLUSIVE PRICE ====================
function formatPrice(amount) {
  return amount % 1 === 0 ? String(amount) : amount.toFixed(2);
}

function addTaxInclusivePrice(card) {
  if (card.getAttribute('data-exec-tax-processed') === 'true') return;
  const data = parsePriceData(card);
  if (!data) {
    const hotelId = card.getAttribute('data-hotel-id') || 'unknown';
    dbg('No tax data for hotel', hotelId, ', skipping');
    return;
  }

  sendPriceSnapshot(card, data);

  const total = data.basePrice + data.tax;
  const perNight = total / data.nights;
  const basePriceStr = formatPrice(data.basePrice);
  const totalStr = formatPrice(total);
  const perNightStr = formatPrice(Math.round(perNight));

  const offerPrice = card.querySelector('p.offer-price');
  if (!offerPrice) return;

  offerPrice.classList.add('exec-tax-styled');
  if (data.nights > 1) {
    offerPrice.innerHTML = `Total: <span class="exec-tax-total">${data.currency}${totalStr}</span> w/ Tax <span class="exec-tax-per-night">(${data.currency}${perNightStr}/night)</span>`;
  } else {
    offerPrice.innerHTML = `Total: <span class="exec-tax-total">${data.currency}${totalStr}</span> w/ Tax`;
  }

  // Show public (non-member) price if available
  if (data.publicPrice && data.publicPrice > data.basePrice) {
    const publicStr = formatPrice(data.publicPrice);
    const publicEl = document.createElement('span');
    publicEl.className = 'exec-public-price';
    publicEl.textContent = ` Was ${data.currency}${publicStr}`;
    offerPrice.appendChild(publicEl);
  }

  // Replace tax details with "From $XX + Taxes $YY"
  const taxEl = card.querySelector('span.stay-details__formatted-tax-type');
  if (taxEl && !card.querySelector('.exec-base-price')) {
    const taxStr = formatPrice(data.tax);
    const baseSpan = document.createElement('span');
    baseSpan.className = 'exec-base-price';
    baseSpan.textContent = `From ${data.currency}${basePriceStr} + Taxes ${data.currency}${taxStr}`;
    taxEl.parentNode.replaceChild(baseSpan, taxEl);
  }

  card.setAttribute('data-exec-tax-processed', 'true');
}

// Helper: get number of nights from URL (tries nights param, then dateIn/dateOut)
function getNightsFromUrl() {
  const params = new URLSearchParams(location.search);
  const n = parseInt(params.get('nights'), 10);
  if (n > 0) return n;
  const dateIn = params.get('dateIn');
  const dateOut = params.get('dateOut');
  if (dateIn && dateOut) {
    const diff = (new Date(dateOut) - new Date(dateIn)) / (1000 * 60 * 60 * 24);
    if (diff > 0) return Math.round(diff);
  }
  return 1;
}

// ==================== SUPABASE DATA COLLECTION ====================
// When the extension is reloaded/updated, content scripts on already-open tabs
// lose their chrome.runtime link. sendMessage then throws "Extension context
// invalidated" and the snapshot is dropped. Detect this once and log a clear
// instruction, so silent data loss becomes obvious.
let _extensionContextInvalidated = false;
// Called once when we detect the content script has been orphaned (extension
// reloaded/updated under an open tab). Warns the user and shuts down all
// recurring work — the route-watch interval and the mutation observer — so the
// dead script goes quiet instead of re-running init()/injectAllRatePanels() on
// every poll and re-hitting these warnings forever. See shutdownExtension().
function markContextInvalidated() {
  if (_extensionContextInvalidated) return;
  _extensionContextInvalidated = true;
  console.warn('[AccorExt] Extension context invalidated — reload this tab to resume price capture.');
  try { shutdownExtension(); } catch (e) { /* shutdown is best-effort */ }
}
function safeSendMessage(msg, callback) {
  if (_extensionContextInvalidated) return;
  if (!chrome.runtime || !chrome.runtime.id) {
    markContextInvalidated();
    return;
  }
  try {
    if (callback) chrome.runtime.sendMessage(msg, callback);
    else chrome.runtime.sendMessage(msg);
  } catch (e) {
    if (e && /Extension context invalidated/i.test(e.message || '')) {
      markContextInvalidated();
    } else {
      console.warn('[AccorExt] sendMessage error:', e);
    }
  }
}

function getDatesFromUrl() {
  const params = new URLSearchParams(location.search);
  const checkin = params.get('dateIn') || null;
  let checkout = params.get('dateOut') || null;
  if (!checkout && checkin) {
    const nights = parseInt(params.get('nights'), 10);
    if (nights > 0) {
      const d = new Date(checkin);
      d.setDate(d.getDate() + nights);
      checkout = d.toISOString().split('T')[0];
    }
  }
  return { checkin, checkout };
}

function getCityFromUrl() {
  const params = new URLSearchParams(location.search);
  // Try common query params
  for (const key of ['destination', 'city', 'locationName']) {
    const val = params.get(key);
    if (val) return val;
  }
  // Try extracting from path: /booking/search/LANG/CITY/... or /booking/hotel/ID/CITY/...
  const parts = location.pathname.split('/').filter(Boolean);
  for (let i = 0; i < parts.length; i++) {
    if (parts[i] === 'search' && parts[i + 2]) return decodeURIComponent(parts[i + 2]);
    if (parts[i] === 'hotel' && parts[i + 2]) return decodeURIComponent(parts[i + 2]);
  }
  return null;
}

function sendPriceSnapshot(card, priceData) {
  try {
    const hotelId = card.getAttribute('data-hotel-id') || 'unknown';
    const nameEl = card.querySelector('[class*="hotel-name"]') || card.querySelector('h2') || card.querySelector('h3');
    const hotelName = nameEl ? nameEl.textContent.trim() : null;
    const dates = getDatesFromUrl();
    const total = priceData.basePrice + priceData.tax;
    // Try city from URL, then from card address/location element
    let city = getCityFromUrl();
    if (!city) {
      const addrEl = card.querySelector('[class*="address"]') || card.querySelector('[class*="location"]') || card.querySelector('[class*="city"]');
      if (addrEl) city = addrEl.textContent.trim();
    }
    safeSendMessage({
      type: 'PRICE_SNAPSHOT',
      data: {
        hotel_id: hotelId,
        hotel_name: hotelName,
        city: city,
        currency: priceData.currency,
        base_price: priceData.basePrice,
        tax_amount: priceData.tax,
        total_price: total,
        per_night: Math.round((total / priceData.nights) * 100) / 100,
        nights: priceData.nights,
        checkin: dates.checkin,
        checkout: dates.checkout,
        has_lounge: EXECUTIVE_LOUNGE_HOTEL_IDS.has(hotelId),
        has_breakfast: FREE_BREAKFAST_HOTEL_IDS.has(hotelId),
        public_price: priceData.publicPrice,
        promo_text: card.getAttribute('data-exec-promo-text') || null,
        page_url: location.href
      }
    });
  } catch (e) { dbg('sendPriceSnapshot error:', e); }
}

function sendRateSnapshots(offers, hotelId, nights) {
  try {
    const dates = getDatesFromUrl();
    const rates = [];
    let currency = null;
    for (const offer of offers) {
      const mainPrice = offer.pricing && offer.pricing.main;
      const memberPrice = (mainPrice && mainPrice.amount) || null;
      const publicPrice = (offer.pricing && offer.pricing.alternative && offer.pricing.alternative.amount) || null;
      const taxText = (offer.pricing && offer.pricing.formattedTaxType) || '';
      const taxParsed = parseCurrencyAmount(taxText);
      const taxAmount = taxParsed ? taxParsed.amount : null;
      const total = (memberPrice && taxAmount != null) ? memberPrice + taxAmount : memberPrice;
      const formattedBase = (mainPrice && mainPrice.formattedAmount) || '';
      if (!currency) { const m = formattedBase.match(/([^\d.,\s]+)/); if (m) currency = m[1].trim(); }
      const policies = (mainPrice && mainPrice.simplifiedPolicies) || {};
      rates.push({
        room: (offer.accommodation && offer.accommodation.name) || null,
        rate: (offer.resolvedRate && offer.resolvedRate.label) || 'Standard Rate',
        type: offer.type || null,
        member: memberPrice,
        public: publicPrice,
        tax: taxAmount,
        total: total,
        meal: (offer.mealPlan && offer.mealPlan.label) || null,
        cancel: (policies.cancellation && policies.cancellation.label) || null
      });
    }
    if (rates.length > 0) {
      safeSendMessage({
        type: 'RATE_SNAPSHOT',
        data: {
          hotel_id: hotelId,
          currency: currency,
          nights: nights,
          checkin: dates.checkin,
          checkout: dates.checkout,
          num_rates: rates.length,
          rates: rates,
          page_url: location.href
        }
      });
    }
  } catch (e) { dbg('sendRateSnapshots error:', e); }
}

