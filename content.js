// No caching — an early call (before offer elements render) used to lock a
// broad fallback selector forever. The querySelector cost is negligible and
// the iteration is short. Always pick the narrowest selector that matches now.
function findRoomsSelector() {
  for (const sel of ROOM_SELECTORS) {
    if (document.querySelector(sel)) return sel;
  }
  return '.hotel-accommodation';
}

function findRoomsContainer() {
  for (const sel of ROOM_SELECTORS) {
    const el = document.querySelector(sel);
    if (el) {
      dbg('Found rooms container with selector:', sel);
      return el;
    }
  }
  return null;
}

function injectShowAllRatesButton() {
  if (document.getElementById('show-all-rates-btn')) return;
  if (!isHotelDetailPage()) return;

  const roomsContainer = findRoomsContainer();
  if (!roomsContainer) {
    dbg('No rooms container found yet');
    return;
  }

  const btn = document.createElement('button');
  btn.id = 'show-all-rates-btn';
  btn.type = 'button';
  btn.addEventListener('click', toggleShowAllRates);

  const wrapper = document.createElement('div');
  wrapper.id = 'show-all-rates-wrapper';
  wrapper.style.cssText = 'padding: 8px 16px; display: flex; align-items: center;';
  wrapper.appendChild(btn);

  roomsContainer.parentNode.insertBefore(wrapper, roomsContainer);
  updateShowAllRatesButton();
  dbg('Show All Rates button injected');
}

function updateShowAllRatesButton() {
  const btn = document.getElementById('show-all-rates-btn');
  if (!btn) return;
  if (showAllRatesActive) {
    btn.classList.add('active');
    btn.textContent = '\u2713 Hide All Rates';
  } else {
    btn.classList.remove('active');
    btn.textContent = 'Show All Rates';
  }
}

function toggleShowAllRates() {
  showAllRatesActive = !showAllRatesActive;
  dbg('Toggle Show All Rates:', showAllRatesActive);
  sessionStorage.setItem('execShowAllRatesActive', showAllRatesActive.toString());
  updateShowAllRatesButton();
  if (showAllRatesActive) {
    showAllRatesRetryCount = 0;
    injectAllRatePanels();
  } else {
    removeAllRatePanels();
  }
}

// ==================== TOGGLE FEATURE ====================
function cardPassesFilter(hotelId) {
  if (loungeFilterMode === 'off') return true;
  if (loungeFilterMode === 'official') return EXECUTIVE_LOUNGE_HOTEL_IDS.has(hotelId);
  return hasAnyBenefit(hotelId); // 'all'
}

function applyFilterToCard(card) {
  const hotelId = card.getAttribute('data-hotel-id');
  if (!hotelId) return;
  if (!cardPassesFilter(hotelId)) {
    card.classList.add('exec-lounge-hidden');
  } else {
    card.classList.remove('exec-lounge-hidden');
  }
}

function applyFilterToAllCards() {
  const cards = document.querySelectorAll('div.result-list-item[data-hotel-id]');
  cards.forEach(applyFilterToCard);
  updateCounter();
}

function updateCounter() {
  const counter = document.getElementById('exec-lounge-counter');
  if (!counter) return;
  const allCards = document.querySelectorAll('div.result-list-item[data-hotel-id]');
  const totalCards = allCards.length;
  let loungeCount = 0;
  let perkCount = 0;
  allCards.forEach(card => {
    const hotelId = card.getAttribute('data-hotel-id');
    if (EXECUTIVE_LOUNGE_HOTEL_IDS.has(hotelId)) loungeCount++;
    else if (isUnofficialBenefit(hotelId)) perkCount++;
  });

  // Per-city, so an unresearched city never reads as "no perks here".
  const researched = isCityResearched();
  const notResearched = researched === false || researched === null;
  const gap = notResearched ? ' \u00b7 perks not yet researched for this city' : '';

  if (loungeFilterMode === 'all') {
    counter.textContent = notResearched
      ? `Showing ${loungeCount + perkCount} of ${totalCards} \u2014 ${loungeCount} official lounge${gap}`
      : `Showing ${loungeCount + perkCount} of ${totalCards} \u2014 ${loungeCount} official lounge, ${perkCount} researched perk`;
  } else if (loungeFilterMode === 'official') {
    counter.textContent = `Showing ${loungeCount} of ${totalCards} hotels with Executive Lounge`;
  } else if (perkCount > 0) {
    counter.textContent = `${loungeCount} of ${totalCards} have an Executive Lounge \u00b7 ${perkCount} more with researched perks`;
  } else {
    counter.textContent = `${loungeCount} of ${totalCards} hotels have an Executive Lounge${gap}`;
  }

  // Make the gap visible on the button too \u2014 the counter is easy to miss, and
  // an empty "Lounges + Perks" result is otherwise indistinguishable from
  // "we looked and there is nothing here".
  const btn = document.getElementById('exec-lounge-toggle-btn');
  if (btn && loungeFilterMode === 'all' && notResearched) {
    btn.textContent = '\u2713 Lounges + Perks (city not researched)';
    btn.title = 'No perk research exists for this city yet, so only official lounges are shown.';
  }
}

function updateToggleButton() {
  const btn = document.getElementById('exec-lounge-toggle-btn');
  if (!btn) return;
  btn.classList.toggle('active', loungeFilterMode !== 'off');
  if (loungeFilterMode === 'official') {
    btn.textContent = '\u2713 Lounge Only';
    btn.title = 'Showing Accor\u2019s official Executive Lounge list. Click for lounges + researched perks.';
  } else if (loungeFilterMode === 'all') {
    btn.textContent = '\u2713 Lounges + Perks';
    btn.title = 'Showing official lounges plus researched unofficial perks. Click to clear.';
  } else {
    btn.textContent = 'Lounge Only';
    btn.title = 'Click to filter to Accor\u2019s official Executive Lounge list.';
  }
}

function toggleFilter() {
  const next = (FILTER_MODES.indexOf(loungeFilterMode) + 1) % FILTER_MODES.length;
  loungeFilterMode = FILTER_MODES[next];
  loungeFilterActive = loungeFilterMode !== 'off';
  sessionStorage.setItem('execLoungeFilterMode', loungeFilterMode);
  sessionStorage.setItem('execLoungeToggleActive', loungeFilterActive.toString());
  updateToggleButton();
  applyFilterToAllCards();
}

function injectToggleButton() {
  if (document.getElementById('exec-lounge-toggle-btn')) return;

  // Try to find the results header area
  const resultsHeader = document.querySelector('.availability-status-message')
    || document.querySelector('[class*="results-header"]')
    || document.querySelector('[class*="search-results"] h1')
    || document.querySelector('[class*="hotel-count"]')
    || document.querySelector('[class*="result-count"]');

  // Create toggle button
  const btn = document.createElement('button');
  btn.id = 'exec-lounge-toggle-btn';
  btn.type = 'button';
  btn.addEventListener('click', toggleFilter);

  // Create counter
  const counter = document.createElement('span');
  counter.id = 'exec-lounge-counter';

  // Create wrapper
  const wrapper = document.createElement('div');
  wrapper.id = 'exec-lounge-toggle-wrapper';
  wrapper.style.cssText = 'padding: 8px 16px; display: flex; align-items: center; flex-wrap: wrap;';
  wrapper.appendChild(btn);
  wrapper.appendChild(counter);

  if (resultsHeader) {
    resultsHeader.parentNode.insertBefore(wrapper, resultsHeader.nextSibling);
  } else {
    // Fallback: insert before the first result card
    const firstCard = document.querySelector('div.result-list-item[data-hotel-id]');
    if (firstCard && firstCard.parentNode) {
      firstCard.parentNode.insertBefore(wrapper, firstCard);
    } else {
      // Last resort: try again later via observer
      return;
    }
  }

  // Set initial state
  updateToggleButton();
  updateCounter();
}

// ==================== MUTATION OBSERVER ====================
let observer = null;
let observerDebounceTimer = null;
let pendingMutations = [];
let routeWatchTimer = null;

function processMutations() {
  // The extension was reloaded out from under this tab, orphaning this content
  // script. Stop all DOM work so it goes quiet instead of re-processing every
  // SPA mutation forever (each batch otherwise re-arms the observer below and
  // re-enters safeSendMessage). The one-time invalidation warning has already
  // told the user to reload the tab.
  if (_extensionContextInvalidated) { stopObserver(); pendingMutations = []; return; }
  observer.disconnect();
  // Everything below runs between a disconnect and a re-observe. Any throw in
  // here used to skip the re-observe at the bottom, permanently switching off
  // every feature on the page (silently — no badges, no panels, no prices)
  // until the tab was reloaded. Re-observe in a finally so one bad DOM shape
  // costs us a single batch instead of the whole session.
  try {
    processMutationBatch();
  } catch (e) {
    console.error('[AccorExt] processMutations error:', e);
  } finally {
    // stopObserver() may have run inside the batch (context invalidated).
    if (observer) observer.observe(document.body, { subtree: true, childList: true });
  }
}

function processMutationBatch() {
  // Drain first: a throw mid-batch must not leave these queued for the next
  // batch to re-process forever.
  const batch = pendingMutations;
  pendingMutations = [];
  // Process accumulated mutations for new hotel cards
  for (const mutation of batch) {
    for (const node of mutation.addedNodes) {
      if (node.nodeType !== Node.ELEMENT_NODE) continue;
      if (node.classList && node.classList.contains('result-list-item') && node.hasAttribute('data-hotel-id')) {
        highlightCard(node);
        addBreakfastBadge(node);
        addPromoBadge(node);
        applyFilterToCard(node);
        addTaxInclusivePrice(node);
      }
      if (node.querySelectorAll) {
        node.querySelectorAll('div.result-list-item[data-hotel-id]').forEach(card => {
          highlightCard(card);
          addBreakfastBadge(card);
          addBenefitBadge(card);
          addPromoBadge(card);
          applyFilterToCard(card);
          addTaxInclusivePrice(card);
        });
      }
    }
  }
  // Update counter when new cards are added
  updateCounter();
  // Try to inject toggle button if it hasn't been placed yet
  if (!document.getElementById('exec-lounge-toggle-btn')) {
    injectToggleButton();
  }
  // Show All Rates: inject button and re-inject panels for new rooms
  if (!document.getElementById('show-all-rates-btn')) {
    injectShowAllRatesButton();
  }
  if (showAllRatesActive) {
    const rooms = document.querySelectorAll(findRoomsSelector());
    const needsReinject = [...rooms].some(r =>
      !r.querySelector('.ext-all-rates-panel') &&
      !r.classList.contains('hotel-accommodation--selected') &&
      r.offsetHeight > 0
    );
    if (needsReinject) injectAllRatePanels();
  }
  // Detail page: badges, tax-inclusive prices, and loyalty
  if (isHotelDetailPage()) {
    injectDetailPageBadges();
    addTaxToDetailPageRooms();
    injectLoyaltyBadge();
    if (detectedLoyaltyTier) markUpgradeEligibleRooms();
  }
  // Benefits box on both search and detail pages
  injectBenefitsBox();
}

function startObserver() {
  if (observer) return;
  observer = new MutationObserver((mutations) => {
    pendingMutations.push(...mutations);
    if (observerDebounceTimer) return;
    // setTimeout, not requestAnimationFrame: rAF callbacks do not fire while a
    // tab is hidden, so the first mutation in a background tab latched this
    // debounce flag and never cleared it — every later mutation then hit the
    // early return above and no observer-driven injection ever ran again.
    // Open a hotel page in a background tab (cmd+click from the results list)
    // and the detail page stayed bare: no rate panels, no badges, no prices.
    // Background timers are throttled to ~1s, which is fine for batching here.
    observerDebounceTimer = setTimeout(() => {
      observerDebounceTimer = null;
      processMutations();
    }, 100);
  });
  observer.observe(document.body, { subtree: true, childList: true });
}

function stopObserver() {
  if (observerDebounceTimer) {
    clearTimeout(observerDebounceTimer);
    observerDebounceTimer = null;
  }
  if (observer) {
    observer.disconnect();
    observer = null;
  }
}

// Stop every recurring driver this content script owns. Called once from
// markContextInvalidated() so an orphaned script (extension reloaded under an
// open tab) stops doing work entirely until the tab is reloaded.
function shutdownExtension() {
  stopObserver();
  if (routeWatchTimer) {
    clearInterval(routeWatchTimer);
    routeWatchTimer = null;
  }
}

// ==================== INIT ====================
// Run one startup step in isolation. init() drives every feature plus the
// MutationObserver that keeps them alive on this SPA, so a throw in an early
// step used to abort all the later ones — including startObserver(), which
// left the page with nothing but our stylesheet.
function step(name, fn) {
  try { fn(); } catch (e) { console.error('[AccorExt] init step "' + name + '" failed:', e); }
}

function init() {
  // Orphaned content script (extension reloaded under this tab) — do nothing.
  if (_extensionContextInvalidated) return;
  // Only run on booking pages
  if (!/\/booking\//i.test(location.pathname)) return;
  dbg('init() running - found booking page');
  loungeFilterActive = sessionStorage.getItem('execLoungeToggleActive') === 'true';
  showAllRatesActive = sessionStorage.getItem('execShowAllRatesActive') !== 'false';
  step('injectStyles', injectStyles);
  step('highlightCards', () => highlightCards());
  step('injectToggleButton', injectToggleButton);
  step('applyFilterToAllCards', applyFilterToAllCards);
  step('injectDetailPageBadges', injectDetailPageBadges);
  step('injectShowAllRatesButton', injectShowAllRatesButton);
  if (showAllRatesActive) {
    showAllRatesRetryCount = 0;
    step('injectAllRatePanels', injectAllRatePanels);
  }
  step('addTaxToDetailPageRooms', addTaxToDetailPageRooms);
  // Not only from processMutations/detectAndCacheLoyaltyTier: with a tier
  // already cached in sessionStorage, detection early-returns and the box
  // would wait on a mutation that may never come.
  step('injectBenefitsBox', injectBenefitsBox);
  step('startObserver', startObserver);
  // Loyalty detection: restore cached tier or detect async
  detectedLoyaltyTier = sessionStorage.getItem('execLoyaltyTier') || null;
  loyaltyDetectionDone = detectedLoyaltyTier !== null;
  step('detectAndCacheLoyaltyTier', detectAndCacheLoyaltyTier); // async, non-blocking
}

// Load fresh hotel data from background.js cache (synced from Supabase)
try {
  chrome.runtime.sendMessage({ type: 'GET_HOTEL_DATA' }, (response) => {
    if (chrome.runtime.lastError || !response) return;
    if (response.loungeIds && response.loungeIds.length > 0) {
      EXECUTIVE_LOUNGE_HOTEL_IDS = new Set(response.loungeIds);
      dbg('Loaded', EXECUTIVE_LOUNGE_HOTEL_IDS.size, 'lounge IDs from Supabase cache');
    }
    if (response.breakfastIds && response.breakfastIds.length > 0) {
      FREE_BREAKFAST_HOTEL_IDS = new Set(response.breakfastIds);
      dbg('Loaded', FREE_BREAKFAST_HOTEL_IDS.size, 'breakfast IDs from Supabase cache');
    }
    if (response.benefits) {
      HOTEL_BENEFITS = response.benefits;
      BENEFIT_CITIES = response.benefitCities || {};
      dbg('Loaded', Object.keys(HOTEL_BENEFITS).length, 'benefit records from Supabase cache');
    }
    // Panels now live on document.body, so clear any open one here rather than
    // per-card — its anchor badge is about to be removed and re-created.
    closeBenefitPanels();
    // Re-process cards with fresh data (fixes race condition with init())
    document.querySelectorAll('div.result-list-item[data-hotel-id]').forEach(card => {
      card.removeAttribute('data-exec-lounge-highlighted');
      card.classList.remove('exec-lounge-highlighted');
      const oldBadge = card.querySelector('.exec-lounge-badge');
      if (oldBadge) oldBadge.remove();
      card.removeAttribute('data-breakfast-badge');
      card.classList.remove('free-breakfast-only');
      const oldBfBadge = card.querySelector('.free-breakfast-badge');
      if (oldBfBadge) oldBfBadge.remove();
      // Benefits arrive in this same response, so clear their badge/panel too —
      // otherwise data-benefit-badge blocks the re-render and cards keep the
      // pre-sync state.
      card.removeAttribute('data-benefit-badge');
      const oldPerkBadge = card.querySelector('.exec-benefit-badge');
      if (oldPerkBadge) oldPerkBadge.remove();
      highlightCard(card);
      addBreakfastBadge(card);
      addBenefitBadge(card);
    });
    // 'all' mode filters on benefit data that only just arrived, so re-apply
    // rather than only refreshing the count.
    applyFilterToAllCards();
    updateToggleButton();
  });
} catch (e) { /* fallback to hardcoded Sets */ }

init();

// v2.2: Watch for route changes on ALL Accor booking pages
(function watchRouteChanges() {
  // Only watch for route changes if we started on a booking page
  if (!/\/booking\//i.test(location.pathname)) return;
  let lastUrl = location.href;
  routeWatchTimer = setInterval(() => {
    if (_extensionContextInvalidated) return;
    if (location.href === lastUrl) return;
    lastUrl = location.href;
    // Clear tax-processed flags so prices recompute on date/currency changes
    document.querySelectorAll('[data-exec-tax-processed]').forEach(el => {
      el.removeAttribute('data-exec-tax-processed');
    });
    // Invalidate caches on route change
    _isDetailPageCached = null;
    // Clean up injected panels on route change
    removeAllRatePanels();
    document.querySelectorAll('.exec-detail-tax').forEach(el => el.remove());
    document.getElementById('exec-loyalty-badge')?.remove();
    document.querySelectorAll('.exec-upgrade-indicator').forEach(el => el.remove());
    const oldBadges = document.getElementById('exec-detail-badges');
    if (oldBadges) oldBadges.remove();
    showAllRatesActive = sessionStorage.getItem('execShowAllRatesActive') !== 'false';
    const isTarget = /all\.accor\.com\/booking/i.test(location.href);
    stopObserver();
    if (isTarget) init();
  }, 1000);
})();
